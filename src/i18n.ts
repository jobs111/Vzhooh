export type Lang = 'ru' | 'en';
export let lang: Lang = conf.get<Lang | ''>('lang', '') || ((navigator.language || 'ru').toLowerCase().startsWith('ru') ? 'ru' : 'en');
export function setLang(l: Lang) { lang = l; conf.set('lang', l); document.documentElement.lang = l; }
export function t(k: string, ...a: (string | number)[]): string {
  const e = S[k];
  let s = e ? e[lang === 'ru' ? 0 : 1] : k;
  a.forEach((v, i) => { s = s.replace('{' + i + '}', String(v)); });
  return s;
}
